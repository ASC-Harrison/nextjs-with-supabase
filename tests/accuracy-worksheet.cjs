const fs=require("node:fs"),ts=require("typescript"),assert=require("node:assert/strict");
const compiled={exports:{}};
const output=ts.transpileModule(fs.readFileSync("lib/accuracy-worksheet.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText;
new Function("exports","require",output)(compiled.exports,require);
const {worksheetEntry,createAccuracyWorksheet}=compiled.exports;
const item={item_id:"one",name:"Adaptic dressing",vendor:"Cardinal Health",reference_number:"6113",shelf:"A1",unit:"BX",on_hand:12,assigned:true,is_active:true,last_verification:null};
const draft={value:"0",expected:12,unit:"BX",status:"pending"};
assert.equal(worksheetEntry(item).value,"","Uncounted items stay blank, even with existing stock");
assert.equal(worksheetEntry(item,draft).value,"0","A typed zero survives export");
assert.match(worksheetEntry(item,draft).status,/UNSAVED/);
const verified={...item,last_verification:{actual_on_hand:8,verified_at:"2026-10-21T14:00:00Z",verified_by:"Jeremy"}};
assert.equal(worksheetEntry(verified).value,"8","Saved server counts included on devices without local drafts");
assert.equal(worksheetEntry(verified,{...draft,value:"4",status:"saved",saved_at:"2026-10-20T14:00:00Z"}).value,"8","Newer server count beats an older saved draft");
assert.equal(worksheetEntry(verified,draft).value,"0","Unsaved local entries retained separately from live stock");
assert.match(worksheetEntry({...item,unit:"EA"},draft).status,/entered in BX/,"Old-unit entries are labeled for review");
assert.match(worksheetEntry(item,{...draft,status:"error"}).status,/review/);
(async()=>{
  const rows=Array.from({length:625},(_,index)=>({...item,item_id:String(index),name:`Supply ${String(index+1).padStart(3,"0")} - Long product description with size and package details`,assigned:index%3!==0,is_active:index!==624}));
  rows[0]={...rows[0],name:"Adaptic dressing - sterile 3 x 3 box"};
  rows[1]={...rows[1],last_verification:verified.last_verification};
  rows[2]={...rows[2],name:"Special product \u2013 size 1\u00bd \u03bc / \ud83d\udce6"};
  const bytes=await createAccuracyWorksheet(rows,{"0":draft},"Main Sterile Supply",new Date("2026-10-21T14:30:00Z"),{regular:fs.readFileSync("public/fonts/Vera.ttf"),bold:fs.readFileSync("public/fonts/VeraBd.ttf")});
  const {PDFDocument}=require("pdf-lib");const doc=await PDFDocument.load(bytes);
  assert.ok(doc.getPageCount()>20,"Full 625-item catalog is paginated");
  assert.equal(doc.getPage(0).getWidth(),792);
  assert.equal(doc.getPage(0).getHeight(),612);
  if(process.env.QA_PDF_PATH)fs.writeFileSync(process.env.QA_PDF_PATH,bytes);
  console.log(`Worksheet counts, units, draft precedence, and ${doc.getPageCount()}-page PDF checks passed.`);
})().catch(error=>{console.error(error);process.exitCode=1;});
